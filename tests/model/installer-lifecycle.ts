const APP_ID = 'com.readandlistenbook.desktop'
const GUID = String(UUID.v5(APP_ID, UUID.parse('50e065bc-3134-11e6-9bab-38c9862bdaf3')))
const VERSION = /^(0|[1-9]\d*)\.(0|[1-9]\d*)\.(0|[1-9]\d*)-dev\.(0|[1-9]\d*)(?![\s\S])/
const SHA = /^[a-f0-9]{64}(?![\s\S])/
const execute = promisify(execFile)
const object = (value: unknown): value is Record<string, unknown> =>
  !!value && typeof value === 'object' && !Array.isArray(value)

export function assertLifecycleRunner(environment: NodeJS.ProcessEnv, platform = process.platform) {
  assert(
    platform === 'win32' &&
      environment.CI === 'true' &&
      environment.GITHUB_ACTIONS === 'true' &&
      environment.RUNNER_OS === 'Windows' &&
      environment.PAGEECHO_INSTALLER_LIFECYCLE === '1' &&
      environment.RUNNER_TEMP &&
      isAbsolute(environment.RUNNER_TEMP),
    'Real installation requires PAGEECHO_INSTALLER_LIFECYCLE=1 on a disposable Windows Actions runner',
  )
  assert(
    !Object.keys(environment).some((key) => /^RALB_/i.test(key)),
    'Do not redirect application data or preload test application settings',
  )
}

export function parseLifecycleArguments(args: string[]) {
  assert(
    args.length === 4 && args[0] === '--build-list' && args[2] === '--output',
    'Use --build-list <two verified builds> --output <fresh cache evidence directory>',
  )
  for (const arg of [args[1], args[3]]) assert(arg && !arg.startsWith('--') && !arg.includes('\0'))
  const output = resolve(args[3]!),
    local = relative(resolve('cache'), output)
  assert(
    local && !isAbsolute(local) && local !== '..' && !local.startsWith('..' + sep),
    'Evidence must use a fresh cache subdirectory',
  )
  return { buildList: resolve(args[1]!), output }
}

export function validateBuildList(value: unknown) {
  assert(
    Array.isArray(value) && value.length === 2,
    'Exactly two historical/candidate builds are required',
  )
  return value.map((item) => {
    assert(
      object(item) &&
        Object.keys(item).sort().join(',') === 'report,sourceCommit,version' &&
        typeof item.sourceCommit === 'string' &&
        /^[a-f0-9]{40}(?![\s\S])/.test(item.sourceCommit) &&
        typeof item.version === 'string' &&
        VERSION.test(item.version) &&
        typeof item.report === 'string' &&
        isAbsolute(item.report) &&
        !item.report.includes('\0'),
      'Invalid installer build provenance',
    )
    return { sourceCommit: item.sourceCommit, version: item.version, report: item.report }
  })
}

export function assertUpgradeVersions(baseline: string, candidate: string) {
  const before = VERSION.exec(baseline)?.slice(1).map(Number),
    after = VERSION.exec(candidate)?.slice(1).map(Number)
  assert(
    before && after && before.every(Number.isSafeInteger) && after.every(Number.isSafeInteger),
    'Invalid actual preview versions',
  )
  const difference = after
    .map((value, index) => value - before[index]!)
    .find((value) => value !== 0)
  assert(
    difference !== undefined && difference > 0,
    'Candidate must be newer than the historical baseline',
  )
}

/** Parse only the command generated by this project's per-user NSIS template, never a shell. */
export function parseQuietUninstall(command: string, installDirectory: string) {
  const parsed = /^"([^"\r\n]+)" \/currentuser \/S$/i.exec(command)
  assert(
    parsed &&
      parsed[0] === command &&
      ![...command].some((character) => character.charCodeAt(0) < 32) &&
      isAbsolute(parsed[1]!),
    'Unexpected registered quiet uninstall command',
  )
  const executable = resolve(parsed[1]!)
  assert.equal(dirname(executable).toLowerCase(), resolve(installDirectory).toLowerCase())
  assert.equal(basename(executable).toLowerCase(), 'uninstall pageecho.exe')
  return { executable, args: ['/currentuser', '/S'] }
}

async function exists(path: string) {
  try {
    await lstat(path)
    return true
  } catch (error) {
    if ((error as NodeJS.ErrnoException).code === 'ENOENT') return false
    throw error
  }
}
async function digest(path: string) {
  const sum = createHash('sha256')
  for await (const chunk of createReadStream(path)) sum.update(chunk)
  return sum.digest('hex')
}
async function boundedJson(path: string) {
  const info = await lstat(path)
  assert(
    info.isFile() && !info.isSymbolicLink() && info.size < 2 * 1024 ** 2,
    'Invalid bounded installer report',
  )
  return JSON.parse(await readFile(path, 'utf8')) as unknown
}
async function installerReport(item: ReturnType<typeof validateBuildList>[number]) {
  const value = await boundedJson(item.report)
  assert(
    object(value) &&
      value.status === 'built-and-statically-verified' &&
      value.installerBuilt === true &&
      value.appId === APP_ID &&
      typeof value.version === 'string' &&
      VERSION.test(value.version) &&
      value.originalOutUnchanged === true &&
      SHA.test(String(value.buildManifestSha256)) &&
      SHA.test(String(value.dependencyLockSha256)) &&
      object(value.installer) &&
      object(value.unpacked),
    'Use an actual verified isolated NSIS build, not a relabelled directory or incomplete installer',
  )
  assert.equal(
    value.sourceCommit,
    item.sourceCommit,
    'Packaging report must refer to the actual checked-out source commit',
  )
  assert.equal(
    value.version,
    item.version,
    'Packaging report must use the actual selected preview version',
  )
  const installer = value.installer,
    unpacked = value.unpacked
  assert(
    typeof installer.path === 'string' &&
      isAbsolute(installer.path) &&
      SHA.test(String(installer.sha256)) &&
      typeof installer.bytes === 'number' &&
      installer.bytes > 1024 ** 2 &&
      typeof unpacked.executable === 'string' &&
      isAbsolute(unpacked.executable) &&
      SHA.test(String(unpacked.asarSha256)),
  )
  const info = await lstat(installer.path)
  assert(info.isFile() && !info.isSymbolicLink() && info.size === installer.bytes)
  assert.equal(
    await digest(installer.path),
    installer.sha256,
    'Installer bytes changed after packaging',
  )
  return {
    path: resolve(installer.path),
    sha256: String(installer.sha256),
    version: value.version,
    manifestSha256: String(value.buildManifestSha256),
    asarSha256: String(unpacked.asarSha256),
    executableSha256: await digest(unpacked.executable),
    sourceCommit: item.sourceCommit,
    report: item.report,
  }
}

async function powershell(script: string) {
  const { stdout } = await execute(
    join(process.env.SystemRoot ?? 'C:\\Windows', 'System32/WindowsPowerShell/v1.0/powershell.exe'),
    [
      '-NoProfile',
      '-NonInteractive',
      '-Command',
      '[Console]::OutputEncoding=[Text.UTF8Encoding]::new($false); $ErrorActionPreference="Stop"; ' +
        script,
    ],
    {
      windowsHide: true,
      timeout: 15000,
      maxBuffer: 1024 ** 2,
      env: { ...process.env, PAGEECHO_LIFECYCLE_GUID: GUID },
    },
  )
  return JSON.parse(stdout.replace(/^\uFEFF/, '')) as unknown
}

interface Registration {
  hive: string
  key: string
  location: string
  version: string
  quiet: string
}
async function registrations(): Promise<Registration[]> {
  const data = await powershell(`
    $found=@(); $g=$env:PAGEECHO_LIFECYCLE_GUID
    foreach($h in @('CurrentUser','LocalMachine')) { foreach($v in @('Registry64','Registry32')) {
      $b=[Microsoft.Win32.RegistryKey]::OpenBaseKey([Microsoft.Win32.RegistryHive]::$h,[Microsoft.Win32.RegistryView]::$v)
      try {
        $u=$b.OpenSubKey('Software\\Microsoft\\Windows\\CurrentVersion\\Uninstall')
        if($u) { try { foreach($n in $u.GetSubKeyNames()) {
          $k=$u.OpenSubKey($n); try {
            $name=[string]$k.GetValue('DisplayName')
            if($n -eq $g -or $name -match '(?i)PageEcho|ReadAndListenBook|read-and-listen-book|听见书页') {
              $found += [pscustomobject]@{hive=$h;key=$n;location=[string]$k.GetValue('InstallLocation');version=[string]$k.GetValue('DisplayVersion');quiet=[string]$k.GetValue('QuietUninstallString')}
            }
          } finally {if($k){$k.Dispose()}}
        }} finally {$u.Dispose()} }
        $i=$b.OpenSubKey('Software\\'+$g)
        if($i) { try {
          $found += [pscustomobject]@{hive=$h;key='install:'+ $g;location=[string]$i.GetValue('InstallLocation');version='';quiet=''}
        } finally {$i.Dispose()} }
      } finally {$b.Dispose()}
    }}
    ConvertTo-Json -InputObject @($found) -Compress
  `)
  assert(
    Array.isArray(data) &&
      data.every(
        (item) =>
          object(item) &&
          ['hive', 'key', 'location', 'version', 'quiet'].every(
            (key) => typeof item[key] === 'string',
          ),
      ),
    'Invalid Windows installation registry state',
  )
  // HKCU is shared between registry views on some Windows configurations.
  return [
    ...new Map(
      (data as unknown as Registration[]).map((item) => [JSON.stringify(item), item]),
    ).values(),
  ]
}

async function waitFor(check: () => Promise<boolean>, label: string, timeoutMs = 60000) {
  const end = Date.now() + timeoutMs
  while (Date.now() < end) {
    if (await check()) return
    await new Promise((done) => setTimeout(done, 500))
  }
  throw new Error(`Timed out waiting for ${label}; no manual cleanup or security bypass attempted`)
}

async function runOwnedExecutable(
  executable: string,
  args: string[],
  rawNsisDirectory = false,
  evidence: Record<string, unknown> = {},
) {
  const child = spawn(executable, args, {
    windowsHide: true,
    stdio: 'ignore',
    windowsVerbatimArguments: rawNsisDirectory,
  })
  Object.assign(evidence, {
    executable,
    args,
    pid: child.pid,
    timedOut: false,
    childExitObserved: false,
    childCloseObserved: false,
    temporaryDescendantCleanupVerified: false,
  })
  let timer: ReturnType<typeof setTimeout> | undefined
  try {
    await new Promise<void>((done, reject) => {
      timer = setTimeout(() => {
        evidence.timedOut = true
        evidence.launcherKillRequested = child.kill()
        reject(
          new Error(
            'Owned installer/uninstaller timed out; only the owned launcher was stopped. Temporary descendant cleanup not verified; no further installation stage will run.',
          ),
        )
      }, 120000)
      child.once('error', reject)
      child.once('exit', (code, signal) =>
        Object.assign(evidence, { childExitObserved: true, exitCode: code, signal }),
      )
      child.once('close', (code, signal) => {
        evidence.childCloseObserved = true
        return code === 0
          ? done()
          : reject(new Error(`Owned installer/uninstaller exited ${code}/${signal}`))
      })
    })
  } finally {
    clearTimeout(timer)
  }
}

async function dataInventory(directory: string) {
  const hashes: Record<string, string> = {}
  let bytes = 0,
    count = 0
  async function walk(path: string) {
    for (const entry of await readdir(path, { withFileTypes: true })) {
      const file = join(path, entry.name),
        info = await lstat(file)
      assert(!info.isSymbolicLink(), 'Synthetic application data must not contain links')
      if (info.isDirectory()) await walk(file)
      else {
        assert(
          info.isFile() && ++count < 10000 && (bytes += info.size) < 256 * 1024 ** 2,
          'Unexpected application data outside synthetic smoke scope',
        )
        hashes[relative(directory, file).replaceAll(sep, '/')] = await digest(file)
      }
    }
  }
  await walk(directory)
  assert(Object.keys(hashes).length > 0, 'No actual application data to preserve')
  return hashes
}

async function choose(app: ElectronApplication, path: string) {
  await app.evaluate(({ dialog }, file) => {
    dialog.showOpenDialog = async () => ({ canceled: false, filePaths: [file] })
  }, path)
}
async function snapshot(page: Page) {
  return page.evaluate(async () => {
    const state = await window.desktop.getState(),
      reading = await window.desktop.getReadingBooks()
    if (!state.ok || !reading.ok) throw new Error('Cannot read retained application state')
    const book = state.value.books[0],
      episode = book?.episodes[0],
      text = reading.value[0]
    if (!book || !episode || !text) throw new Error('Synthetic books were not retained')
    const target = { episodeId: episode.id, audioHash: episode.contentHash }
    const transcript = await window.desktop.getTranscript(target),
      bookmarks = await window.desktop.getBookmarks({ id: book.id })
    const document = await window.desktop.getReadingPage({ id: text.id, start: 0 })
    if (!transcript.ok || transcript.value.status !== 'ready' || !bookmarks.ok || !document.ok)
      throw new Error('Manual transcript, bookmark or reading document was not retained')
    return {
      audio: {
        bookId: book.id,
        title: book.title,
        episodeId: episode.id,
        hash: episode.contentHash,
        positionMs: episode.positionMs,
        durationMs: episode.durationMs,
        currentEpisodeId: state.value.currentEpisodeId,
        currentBookEpisodeId: book.currentEpisodeId,
        preferences: state.value.preferences,
        skips: [book.introMs, book.outroMs],
      },
      transcript: {
        revision: transcript.value.transcript.revision,
        document: transcript.value.transcript.document,
      },
      bookmarks: bookmarks.value.map((item) => ({
        id: item.id,
        note: item.note,
        positionMs: item.positionMs,
        audioHash: item.audioHash,
        stale: item.stale,
      })),
      reading: {
        id: text.id,
        title: text.title,
        hash: text.hash,
        position: text.position,
        sentences: document.value.sentences,
      },
      readerPreference: localStorage.getItem('ralb:reader:global:v3'),
      theme: localStorage.getItem('ralb:app:theme:v1'),
    }
  })
}

async function lifecycle(args: string[]) {
  assertLifecycleRunner(process.env)
  const options = parseLifecycleArguments(args)
  const builds = validateBuildList(await boundedJson(options.buildList))
  assert.notEqual(
    builds[0]!.sourceCommit,
    builds[1]!.sourceCommit,
    'Baseline must come from a distinct historical source commit',
  )
  const baseline = await installerReport(builds[0]!),
    candidate = await installerReport(builds[1]!)
  assertUpgradeVersions(baseline.version, candidate.version)
  assert.notEqual(
    baseline.sha256,
    candidate.sha256,
    'Upgrade requires different actual installer builds',
  )
  assert.notEqual(baseline.manifestSha256, candidate.manifestSha256)
  const folders = await powershell(
    `[pscustomobject]@{roaming=[Environment]::GetFolderPath('ApplicationData');local=[Environment]::GetFolderPath('LocalApplicationData');desktop=[Environment]::GetFolderPath('Desktop');programs=[Environment]::GetFolderPath('Programs')} | ConvertTo-Json -Compress`,
  )
  assert(
    object(folders) &&
      ['roaming', 'local', 'desktop', 'programs'].every(
        (key) => typeof folders[key] === 'string' && isAbsolute(folders[key] as string),
      ),
  )
  assert.equal(
    resolve(process.env.APPDATA ?? '').toLowerCase(),
    resolve(folders.roaming as string).toLowerCase(),
    'APPDATA must be the real current-user default',
  )
  assert.equal(
    resolve(process.env.LOCALAPPDATA ?? '').toLowerCase(),
    resolve(folders.local as string).toLowerCase(),
  )
  const data = join(folders.roaming as string, 'ReadAndListenBook')
  // Fail closed even for an empty existing directory. This harness never adopts or deletes it.
  for (const path of [
    data,
    join(folders.roaming as string, 'ReadAndListenBook-dev'),
    join(folders.roaming as string, 'PageEcho'),
    join(folders.roaming as string, 'read-and-listen-book'),
    join(folders.local as string, 'Programs/PageEcho'),
    join(folders.local as string, 'Programs/read-and-listen-book'),
    join(folders.desktop as string, '听见书页.lnk'),
    join(folders.programs as string, '听见书页.lnk'),
  ])
    assert(
      !(await exists(path)),
      `Existing application installation/data/shortcut; refusing to touch ${path}`,
    )
  assert.deepEqual(
    await registrations(),
    [],
    'Existing application registration; refusing installation',
  )
  const running = await powershell(
    `ConvertTo-Json -InputObject @(Get-Process | Where-Object {$_.ProcessName -match '^(PageEcho|ReadAndListenBook|听见书页)$'} | Select-Object Id,ProcessName) -Compress`,
  )
  assert.deepEqual(running, [], 'An existing application process is running')
  const runnerTemp = await realpath(process.env.RUNNER_TEMP!)
  const work = await mkdtemp(join(runnerTemp, 'pageecho-installer-lifecycle-'))
  await mkdir(dirname(options.output), { recursive: true })
  await mkdir(options.output)
  const install = join(work, '实际 安装'),
    executable = join(install, 'PageEcho.exe')
  const report: Record<string, unknown> = {
    status: 'running',
    startedAt: new Date().toISOString(),
    baseline,
    candidate,
    work,
    install,
    data,
    appId: APP_ID,
    guid: GUID,
    initialDataAbsent: true,
    defaultAppData: true,
    installerExecuted: false,
    upgradeVerified: false,
    uninstallVerified: false,
    reinstallVerified: false,
    cleanDeviceVerified: false,
    ownedExecutables: [],
    scope:
      'Explicit disposable Windows Actions development runner; real per-user NSIS lifecycle and default APPDATA. Not a clean consumer device, signing/SmartScreen/non-admin/UAC or ASR model acceptance.',
  }
  const reportPath = join(options.output, 'report.json')
  const save = () => writeFile(reportPath, JSON.stringify(report, null, 2) + '\n')
  let app: ElectronApplication | undefined,
    stage = 'install-baseline'
  const env: Record<string, string> = {}
  for (const [key, value] of Object.entries(process.env))
    if (
      value !== undefined &&
      !/^(NODE|PYTHON|VIRTUAL_ENV|CONDA|npm_|RALB_|ELECTRON_)/i.test(key) &&
      key.toLowerCase() !== 'path'
    )
      env[key] = value
  env.PATH = join(process.env.SystemRoot ?? 'C:\\Windows', 'System32')
  const errors: string[] = []
  async function runRecorded(executable: string, args: string[], rawNsisDirectory = false) {
    const operation: Record<string, unknown> = { startedAt: new Date().toISOString() }
    ;(report.ownedExecutables as unknown[]).push(operation)
    try {
      await runOwnedExecutable(executable, args, rawNsisDirectory, operation)
    } finally {
      operation.finishedAt = new Date().toISOString()
      await save()
    }
  }
  async function installed(version: string) {
    const all = await registrations(),
      entries = all.filter((item) => !item.key.startsWith('install:'))
    assert.equal(entries.length, 1, 'One application uninstall registration is required')
    assert.equal(
      all.filter((item) => item.key.startsWith('install:')).length,
      1,
      'One NSIS install-location registration is required',
    )
    for (const entry of all) {
      assert.equal(entry.hive, 'CurrentUser', 'Installation must remain per-user')
      assert.equal(entry.key.replace(/^install:/, '').toLowerCase(), GUID.toLowerCase())
      // NSIS stores InstallLocation in Software/<guid>; its uninstall row can omit it.
      if (entry.key.startsWith('install:') || entry.location)
        assert.equal(resolve(entry.location).toLowerCase(), resolve(install).toLowerCase())
    }
    assert.equal(entries[0]!.version, version)
    parseQuietUninstall(entries[0]!.quiet, install)
    return entries[0]!
  }
  async function installBuild(build: typeof candidate) {
    assert.equal(await digest(build.path), build.sha256)
    // NSIS treats every character after /D= as the directory; it must be last and unquoted.
    await runRecorded(build.path, ['/S', '/currentuser', `/D=${install}`], true)
    report.installerExecuted = true
    await waitFor(() => exists(executable), 'installed application executable')
    await installed(build.version)
    assert.equal(await digest(join(install, 'resources/app.asar')), build.asarSha256)
    assert.equal(await digest(executable), build.executableSha256)
  }
  async function launch(build: typeof candidate) {
    app = await electron.launch({
      executablePath: executable,
      args: [],
      cwd: work,
      env,
      timeout: 30000,
    })
    const page = await app.firstWindow()
    page.on('pageerror', (error) => errors.push(error.message))
    await page.context().setOffline(true)
    await expect(page.getByRole('link', { name: '听见书页首页', exact: true })).toBeVisible()
    const identity = await app.evaluate(({ app }) => ({
      packaged: app.isPackaged,
      version: app.getVersion(),
      name: app.getName(),
      exe: app.getPath('exe'),
      userData: app.getPath('userData'),
    }))
    assert(identity.packaged, 'Actual installed PageEcho executable must be packaged')
    assert.equal(identity.version, build.version)
    assert.equal(identity.name, 'ReadAndListenBook')
    assert.equal(resolve(identity.exe).toLowerCase(), resolve(executable).toLowerCase())
    assert.equal(resolve(identity.userData).toLowerCase(), resolve(data).toLowerCase())
    return page
  }
  async function quit() {
    assert(app)
    const closed = await closeOwnedElectron(app)
    app = undefined
    assert.equal(closed.kind, 'graceful', 'Forced termination is not a successful lifecycle exit')
  }
  try {
    await save()
    await installBuild(baseline)
    stage = 'seed-real-default-application-data'
    const page = await launch(baseline)
    const wav = Buffer.alloc(44 + 70 * 16000)
    wav.write('RIFF')
    wav.writeUInt32LE(wav.length - 8, 4)
    wav.write('WAVEfmt ', 8)
    wav.writeUInt32LE(16, 16)
    wav.writeUInt16LE(1, 20)
    wav.writeUInt16LE(1, 22)
    wav.writeUInt32LE(8000, 24)
    wav.writeUInt32LE(16000, 28)
    wav.writeUInt16LE(2, 32)
    wav.writeUInt16LE(16, 34)
    wav.write('data', 36)
    wav.writeUInt32LE(wav.length - 44, 40)
    const audio = join(work, '合成音频 第1集.wav')
    await writeFile(audio, wav)
    await choose(app!, audio)
    const selected = await page.evaluate(() => window.desktop.selectAudio({ kind: 'audio' }))
    assert(selected.ok && !selected.value.canceled)
    const importedBook = await page.evaluate(
      (id) => window.desktop.getBookDetail({ id }),
      selected.value.mutation.bookId!,
    )
    assert(importedBook.ok && importedBook.value)
    const book = importedBook.value,
      episode = book.episodes[0]!
    const transcript = join(work, '合成手工字幕.json')
    await writeFile(
      transcript,
      JSON.stringify({
        version: 1,
        audioHash: episode.contentHash,
        kind: 'manual',
        coverage: [{ startMs: 0, endMs: 70000 }],
        segments: [
          {
            id: 'synthetic-sentence',
            startMs: 1000,
            endMs: 60000,
            text: '这是安装升级验收使用的合成字幕。',
          },
        ],
      }),
    )
    await choose(app!, transcript)
    const imported = await page.evaluate((target) => window.desktop.importTranscript(target), {
      episodeId: episode.id,
      audioHash: episode.contentHash,
    })
    assert(imported.ok && !imported.value.canceled)
    const source = await page.evaluate(
      (id) => window.desktop.openEpisode({ id, requestId: crypto.randomUUID() }),
      episode.id,
    )
    assert(source.ok)
    const progress = await page.evaluate((input) => window.desktop.saveProgress(input), {
      sessionId: source.value.sessionId,
      episodeId: episode.id,
      positionMs: 12345,
      durationMs: 70000,
      rate: 1.25,
      volume: 0.37,
    })
    assert(progress.ok)
    const bookmark = await page.evaluate((target) => window.desktop.saveBookmark(target), {
      episodeId: episode.id,
      audioHash: episode.contentHash,
      positionMs: 12000,
      note: '合成安装升级书签',
    })
    assert(bookmark.ok)
    const text = join(work, '合成阅读书籍.txt')
    await writeFile(
      text,
      '第1章 山路\n清晨的风穿过树梢。\n少年沿着小路前进。\n山间的钟声渐渐远去。\n小船驶向远方。\n第2章 清晨\n第二天的故事仍在继续。',
    )
    await choose(app!, text)
    const reading = await page.evaluate(() => window.desktop.importReadingBook())
    assert(reading.ok && !reading.value.canceled)
    const position = await page.evaluate(
      (id) => window.desktop.saveReadingPosition({ id, position: 3 }),
      reading.value.book.id,
    )
    assert(position.ok)
    await page.evaluate(() => {
      localStorage.setItem(
        'ralb:reader:global:v3',
        JSON.stringify({ fontSize: 26, mode: 'scroll', theme: 'green' }),
      )
      localStorage.setItem('ralb:app:theme:v1', 'dark')
    })
    const expected = await snapshot(page)
    assert.equal(expected.audio.positionMs, 12345)
    assert.deepEqual(expected.audio.preferences, { rate: 1.25, volume: 0.37 })
    assert.equal(expected.reading.position, 3)
    report.seed = {
      ...expected,
      syntheticOnly: true,
      mediaDecoded: false,
      asrExecuted: false,
      requestId: randomUUID(),
    }
    await quit()
    stage = 'upgrade-candidate'
    await installBuild(candidate)
    const upgraded = await launch(candidate)
    assert.deepEqual(
      await snapshot(upgraded),
      expected,
      'Upgrade changed retained content, progress or preferences',
    )
    await quit()
    report.upgradeVerified = true
    stage = 'real-uninstall-default-data-retention'
    const before = await dataInventory(data),
      registration = await installed(candidate.version)
    const command = parseQuietUninstall(registration.quiet, install)
    await runRecorded(command.executable, command.args)
    // NSIS may launch a temporary uninstaller and return before actual removal finishes.
    await waitFor(
      async () => !(await exists(executable)) && (await registrations()).length === 0,
      'real uninstall and registration removal',
    )
    assert.deepEqual(
      await dataInventory(data),
      before,
      'Default uninstall removed or altered application data',
    )
    report.uninstallVerified = true
    report.retainedFileCount = Object.keys(before).length
    stage = 'reinstall-candidate'
    await installBuild(candidate)
    const reinstalled = await launch(candidate)
    assert.deepEqual(
      await snapshot(reinstalled),
      expected,
      'Reinstall did not retain existing default application data',
    )
    await quit()
    report.reinstallVerified = true
    stage = 'final-real-uninstall'
    const finalBefore = await dataInventory(data),
      finalCommand = parseQuietUninstall((await installed(candidate.version)).quiet, install)
    await runRecorded(finalCommand.executable, finalCommand.args)
    await waitFor(
      async () => !(await exists(executable)) && (await registrations()).length === 0,
      'final uninstall',
    )
    assert.deepEqual(await dataInventory(data), finalBefore)
    assert.deepEqual(errors, [])
    assert.equal(await digest(baseline.path), baseline.sha256)
    assert.equal(await digest(candidate.path), candidate.sha256)
    report.status = 'passed'
  } catch (error) {
    report.status = 'failed'
    report.stage = stage
    report.error = error instanceof Error ? error.stack : String(error)
    process.exitCode = 1
  } finally {
    if (app) {
      try {
        report.cleanup = await closeOwnedElectron(app)
      } catch (error) {
        report.status = 'failed'
        report.cleanupError = error instanceof Error ? error.stack : String(error)
        process.exitCode = 1
      }
    }
    // Do not manually delete application data, installation remnants or registry entries.
    report.finishedAt = new Date().toISOString()
    await save()
    console.log(JSON.stringify({ status: report.status, stage, report: reportPath }))
  }
}

